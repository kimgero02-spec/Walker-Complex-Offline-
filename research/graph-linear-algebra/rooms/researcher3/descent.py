def span_basis(vecs):
    """F2 row reduce; return rank and basis"""
    basis=[]
    for x in vecs:
        x=list(x)
        for b in basis:
            piv=next(i for i,c in enumerate(b) if c)
            if x[piv]: x=[(u+w)%2 for u,w in zip(x,b)]
        if any(x): basis.append(x)
    return basis
def kummer_image(th,v,N=60):
    """subgroup of (Q_v^x/sq)^3 generated by deltas of rational points t=a/b; returns set of tuples"""
    gens=[]
    f=lambda t: 2*(t-th[0])*(t-th[1])*(t-th[2])
    pts=[]
    for b in range(1,N):
        for a in range(-N*2,N*2+1):
            if gcd(a,b)!=1: continue
            t=Fraction(a,b)
            F=f(t)
            if F==0:
                continue
            if not is_sq_p(F,v): continue
            d=[2*(t-th[i]) for i in range(3)]
            gens.append(sum((sqclass(x,v) for x in d),()))
    # torsion points
    for i in range(3):
        d=[None]*3
        for j in range(3):
            if j!=i: d[j]=2*(th[i]-th[j])
        d[i]=Fraction(fp(th,i))
        # delta_i = product of others up to square: use 4*f'(th_i)  (=f' mod sq); ensure consistent:
        gens.append(sum((sqclass(x,v) for x in d),()))
    B=span_basis(gens)
    # enumerate span
    S={tuple([0]*len(gens[0]))}
    for b in B:
        S|={tuple((x+y)%2 for x,y in zip(s,b)) for s in S}
    return S,len(B)
def isotropic_class(th,delta,v):
    lam=[Fraction(-2*delta[i],fp(th,i)) for i in range(3)]
    return isotropic_diag(lam,v)
def class_in_set(delta,v,S): return clsvec(delta,v) in S
def local_candidates(th,v):
    """all delta (d1,d2,d3) in H^1(Q_v,E[2]) as local class tuples: enumerate reps"""
    if v==0: reps=[-1,1]
    elif v==2: reps=[1,-1,2,-2,5,-5,10,-10]
    else:
        # nonresidue
        n=next(x for x in range(2,v) if legendre(x,v)==-1)
        reps=[1,n,v,n*v]
    out=[]
    for d1 in reps:
        for d2 in reps:
            for d3 in reps:
                if sum(sqclass(d1*d2*d3,v))==0: out.append((d1,d2,d3))
    return out
