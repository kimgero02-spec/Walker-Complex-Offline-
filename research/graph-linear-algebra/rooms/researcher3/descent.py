def fp(th,i): 
    r=1
    for j in range(3):
        if j!=i: r*=th[i]-th[j]
    return r
def primes_S(th):
    d=1
    for i in range(3):
        for j in range(i+1,3): d*=(th[i]-th[j])
    S={2}
    for q in sp.factorint(abs(d)): S.add(q)
    return sorted(S)
def clsvec(delta,v):
    out=()
    for d in delta: out+=sqclass(d,v)
    return out
