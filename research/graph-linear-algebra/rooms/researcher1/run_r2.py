# R2 researcher1: 추측 1 단계별 확인 (q=3,5,7). 증명의 보조 확인용.
import numpy as np, itertools, sys
from collections import Counter, defaultdict
def run(q):
    A=np.ones((3,3),int)-np.eye(3,dtype=int)
    idx=list(itertools.product(range(q),repeat=6))
    Ms=np.array(idx)
    def mat(r):
        M=np.zeros((len(r),3,3),int)
        M[:,0,0]=r[:,0];M[:,0,1]=M[:,1,0]=r[:,1];M[:,0,2]=M[:,2,0]=r[:,2]
        M[:,1,1]=r[:,3];M[:,1,2]=M[:,2,1]=r[:,4];M[:,2,2]=r[:,5]
        return M
    M=mat(Ms)
    def code(M):
        r=np.stack([M[:,0,0],M[:,0,1],M[:,0,2],M[:,1,1],M[:,1,2],M[:,2,2]],1)%q
        return ((((r[:,0]*q+r[:,1])*q+r[:,2])*q+r[:,3])*q+r[:,4])*q+r[:,5]
    # f: char poly of N=A^-1 M ; compute via det(tA-M)/2 coefficients
    inv2=pow(2,-1,q)
    def det3(X):
        return (X[:,0,0]*(X[:,1,1]*X[:,2,2]-X[:,1,2]*X[:,2,1])-X[:,0,1]*(X[:,1,0]*X[:,2,2]-X[:,1,2]*X[:,2,0])+X[:,0,2]*(X[:,1,0]*X[:,2,1]-X[:,1,1]*X[:,2,0]))
    vals=[]
    for t in range(4):
        vals.append(det3(t*A[None]-M)%q)
    # g(t)=2t^3+g2 t^2+g1 t+g0 ; g(0),g(1),g(2),g(3) -> solve (q>=5), for q=3 use direct expansion instead
    # use symbolic expansion: det(tA-M) coefficients
    tr=M[:,0,0]+M[:,1,1]+M[:,2,2]
    one=M.sum(axis=(1,2))
    g2=(2*tr-one)%q
    g0=(-det3(M))%q
    # g1: sum of 2x2 minors-type: coefficient via g(1)=2+g2+g1+g0
    g1=(vals[1]-2-g2-g0)%q
    fk=np.stack([g2*inv2%q,g1*inv2%q,g0*inv2%q],1)  # f=t^3+a t^2+b t+c
    # sanity: g(2)
    assert np.all((16+4*g2+2*g1+g0-vals[2])%q==0)
    fcode=(fk[:,0]*q+fk[:,1])*q+fk[:,2]
    # orbits under O(A)(F_q): generated by reflections
    rows=[];cols=[]
    N=len(M); base=code(M)
    gens=0
    for v in itertools.product(range(q),repeat=3):
        v=np.array(v)
        n=int(v@A@v)%q
        if n==0: continue
        R=(np.eye(3,dtype=int)-2*pow(n,-1,q)*np.outer(v,A@v))%q
        assert np.all((R.T@A@R-A)%q==0)
        M2=np.einsum('ji,njk,kl->nil',R,M,R)%q
        rows.append(base);cols.append(code(M2));gens+=1
    rows=np.concatenate(rows);cols=np.concatenate(cols)
    lab=np.arange(N)
    while True:
        # label propagation (min label over edges)
        m=np.minimum(lab[rows],lab[cols])
        new=lab.copy()
        np.minimum.at(new,rows,m); np.minimum.at(new,cols,m)
        new=new[new]
        if np.array_equal(new,lab): break
        lab=new
    # squarefree test over F_q
    def roots(a,b,c): return [x for x in range(q) if (x**3+a*x*x+b*x+c)%q==0]
    def sqfree(a,b,c):
        # disc != 0 over F_q (char odd): discriminant of cubic
        d=(18*a*b*c-4*a**3*c+a*a*b*b-4*b**3-27*c*c)%q
        return d!=0
    fib=defaultdict(list)
    for i in range(N): fib[tuple(fk[i])].append(i)
    res=Counter(); bad=0; sizes=Counter(); nsf_sizes=Counter()
    for f,l in fib.items():
        a,b,c=f
        orbs=Counter(lab[l])
        if sqfree(a,b,c):
            r=len(roots(a,b,c)); E2=1+r
            ok=(len(orbs)==E2) and all(s==q*(q*q-1)//E2 for s in orbs.values()) and len(l)==q*(q*q-1)
            if not ok: bad+=1
            res[(r,len(orbs),len(l),tuple(sorted(orbs.values())))]+=1
        else:
            nsf_sizes[len(l)]+=1
    print("q=",q,"reflections",gens,"bad",bad)
    for k,v in sorted(res.items()): print(" (roots,#orbits,fiber,orbit sizes)",k,"x",v)
    print(" non-squarefree fiber sizes",dict(nsf_sizes), "total", sum(k*v for k,v in nsf_sizes.items()))
    # section check
    for f in fib:
        a,b,c=f
        Ms_=np.array([[2*c,b+2*c,0],[b+2*c,2*(a+b+c+1),1],[0,1,0]])%q
        r=np.array([[Ms_[0,0],Ms_[0,1],Ms_[0,2],Ms_[1,1],Ms_[1,2],Ms_[2,2]]])
        idxs=code(mat(r)); 
        assert tuple(fk[idxs[0]])==f, (f,)
    print(" section M(a,b,c) lands in fiber for all",len(fib),"f")
for q in map(int,sys.argv[1:]): run(q)
