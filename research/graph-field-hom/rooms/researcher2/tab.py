def hom(T,f,m):  # Hom(Z^f + ⊕Z/T, Z/m)
    out=[]
    if m==0: # Z
        return ["Z"]*f if f else []
    for t in T: out.append(gcd(t,m))
    out += [m]*f
    return out
for name,(n,arcs) in G.items():
    T,f=AG(n,arcs,-2,1)
    def fmt(m):
        h=hom(T,f,m)
        if m==0: 
            return "Z^%d"%f if f else "0"
        h=[x for x in h if x!=1]
        return "⊕".join("Z/%d"%x for x in h) if h else "0"
    print(f"{name:32s} A_G=Z^{f} ⊕ {T}   Z/4: {fmt(4)} | Z/6: {fmt(6)} | Z: {fmt(0)} | Q: Q^{f}")
